package Arrays;

public class ArrayOfOtherDataTypes {
    public static void main(String[] args) {
        char[] arr = new char[8];
        for (int i=0; i<arr.length;i++){
            System.out.println(arr[i] +" ");
        }
        String[] x = {"sinu", "Tanu", "Pihu","Minu"};
        for (int i=0; i<x.length;i++){
            System.out.println(x[i] +" ");
        }
    }
}
